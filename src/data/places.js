export function autoAround(origin) {
  return around(origin, AUTO_SERVICES).map((s) => ({ ...s, group: 'service' }))
}

export function washAround(origin) {
  return around(origin, WASHES).map((s) => ({
    ...s,
    group: 'wash',
    types: [s.washType],
  }))
}

export function parkingAround(origin) {
  return around(origin, PARKINGS, 4).map((s) => ({
    ...s,
    group: 'parking',
    types: [s.parkingKind],
  }))
}

export function evAround(origin) {
  return around(origin, EV_STATIONS).map((s) => ({
    ...s,
    group: 'ev',
    types: [s.brandId],
    prices: { kwh: s.kwh },
  }))
}

export function foodAround(origin) {
  return around(origin, KITCHENS).map((s) => ({ ...s, group: 'food' }))
}

export function smartPlaces(origin) {
  return [
    ...stationsAround(origin),
    ...autoAround(origin),
    ...washAround(origin),
    ...parkingAround(origin),
    ...evAround(origin),
    ...foodAround(origin),
    ...around(origin, HELP_POINTS).map((s) => s),
  ].sort((a, b) => a.km - b.km)
}

export function parkingColor(kind) {
  if (kind === 'allowed') return '#16a34a'
  if (kind === 'forbidden') return '#ef4444'
  return '#f59e0b'
}

export function washColor(type) {
  return type === 'self' ? '#0ea5e9' : '#a855f7'
}
