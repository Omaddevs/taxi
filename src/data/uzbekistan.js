export function getRegion(name) {
  return REGIONS.find((r) => r.name === name) || null
}

export function formatPlace(region, place) {
  if (!region && !place) return ''
  if (!place) return region
  if (!region) return place
  return `${region}, ${place}`
}

export function searchUzPlaces(query) {
  const q = query.trim().toLowerCase()
  if (q.length < 1) return []
  const hits = []
  for (const region of REGIONS) {
    if (region.name.toLowerCase().includes(q)) {
      hits.push({ type: 'region', region: region.name, place: '' })
    }
    for (const place of region.districts) {
      if (place.toLowerCase().includes(q)) {
        hits.push({ type: 'district', region: region.name, place })
      }
    }
  }
  return hits.slice(0, 24)
}
